-- Master ingredient list. Platform-wide, managed from Super Admin; restaurants import all of it
-- (or single rows) into their own inventory_items from the Inventory page.
-- Seeded from the old PHP `items` table. Stock quantities and prices from that dump were one
-- restaurant's own numbers, so they are not carried over; legacy_unit_type keeps the old 0/1/2
-- unit code so units can be mapped later with one UPDATE once the meaning is confirmed.
create table if not exists public.ingredients (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  category text not null default 'Other',
  item_type text not null default 'ready_made' check (item_type in ('ready_made','self_made')),
  unit text not null default 'pcs',
  legacy_unit_type int,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists ux_ingredients_name on public.ingredients (lower(name));
create index if not exists ix_ingredients_category on public.ingredients (category);

alter table public.ingredients enable row level security;
-- Reads/writes happen through the service-role client (restaurant API routes and Super Admin
-- actions), so no anon/authenticated policy is needed.

